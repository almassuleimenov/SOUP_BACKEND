#!/usr/bin/env python3
"""Build results/INDEX.md from every results/**/summary.json (all runs, failed ones included)."""
import json
import pathlib
import sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "results")
rows = []
for f in sorted(root.rglob("summary.json"), key=lambda p: p.parent.name):  # chronological
    s = json.loads(f.read_text(encoding="utf-8"))
    ev = s.get("evidence", {})
    h = ev.get("harness", {})
    z = ev.get("zombies", {})
    ro = ev.get("run_outcomes", {})
    cp = ev.get("cancel_paths", {})
    failed = [c["name"].split(" ")[0] for c in s.get("checks", []) if c["violations"] > 0]
    args = " ".join(a for a in s.get("args", []) if not a.startswith("postgres://") and not a.startswith("-db"))
    rows.append(
        "| `{run}` | {jobs} | {kills} | {le} | {late} | {fo} | {cr} | {wall:.0f}s | {verdict}{failed} |".format(
            run=f.parent.relative_to(root).as_posix(),
            jobs=sum(ev.get("final_states", {}).values()),
            kills=h.get("kills_sigkill", 0),
            le=ro.get("lease_expired", 0),
            late=z.get("late_writes_rejected_total", 0),
            fo=z.get("fence_only_rejections", "n/a"),
            cr=cp.get("cancelled_by_worker_while_running", 0) + cp.get("cancelled_by_reaper_after_worker_death", 0),
            wall=s.get("wall_seconds", 0),
            verdict=s.get("verdict", "?"),
            failed=(" — " + ", ".join(failed)) if failed else "",
        )
        + f" `{args}` |"
    )

out = [
    "# All harness runs",
    "",
    "Generated by `scripts/index_results.py` from every `summary.json`. Nothing is filtered out: failed runs, blind runs",
    "and runs of builds that were later changed are all here. Raw logs are next to each summary.",
    "",
    "Columns: kills = kill -9 count · lease exp = dead workers detected · late = zombie writes rejected · fence-only =",
    "rejections that only the fencing token could make · cancel run = cancels that hit a running job (worker or reaper).",
    "",
    "| run | jobs | kills | lease exp | late | fence-only | cancel run | wall | verdict | args |",
    "|---|---|---|---|---|---|---|---|---|---|",
    *rows,
    "",
]
(root / "INDEX.md").write_text("\n".join(out), encoding="utf-8")
print(f"{len(rows)} runs indexed -> {root / 'INDEX.md'}")
